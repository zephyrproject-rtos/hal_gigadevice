import argparse
from pathlib import Path
import re
import shutil


REPO_ROOT = Path(__file__).absolute().parents[1]
"""Repository root (used for input/output default folders)."""


def main(hal_path, output):
    """Entry point.

    Args:
        hal_path: HAL repository path.
        output: Output directory.
    """

    # obtain all available APIs for each series
    apis = dict()
    for entry in sorted(hal_path.iterdir()):
        if not entry.is_dir() or not entry.name.startswith("gd32"):
            continue

        # obtain series API headers
        # anchor on series name: both series (gd32h73x_75x) and API
        # (i2c_add) may contain underscores
        series_headers = entry / "standard_peripheral" / "include"
        api_re = re.compile(rf"^{re.escape(entry.name)}_([a-z0-9_]+)\.h$")
        series_apis = dict()
        for header in sorted(series_headers.iterdir()):
            m = api_re.match(header.name)
            if not m:
                continue

            api = m.group(1)

            # ignore libopt (not an API)
            if api == "libopt":
                continue

            series_apis[api] = header.name

        for api, header in series_apis.items():
            # merge companion header (e.g. i2c_add) into its base API (i2c)
            bases = [b for b in series_apis if api.startswith(b + "_")]
            if bases:
                api = max(bases, key=len)

            apis.setdefault(api, dict()).setdefault(entry.name, list())
            apis[api][entry.name].append(header)

    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    for api, all_series in apis.items():
        header_file = output / ("gd32_" + api + ".h")
        with open(header_file, "w") as f:
            f.write("/*\n")
            f.write(" * NOTE: Autogenerated file using gd32headers.py\n")
            f.write(" *\n")
            f.write(" * SPDX-License-Identifier: Apache-2.0\n")
            f.write(" */\n\n")

            for i, (series, headers) in enumerate(all_series.items()):
                f.write("#if" if i == 0 else "#elif")
                f.write(f" defined(CONFIG_SOC_SERIES_{series.upper()})\n")
                for header in headers:
                    f.write(f"#include <{header}>\n")
            f.write("#endif\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "-p",
        "--hal-path",
        type=Path,
        default=REPO_ROOT,
        help="Path to the HAL repository root",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=REPO_ROOT / "common_include",
        help="Output directory",
    )
    args = parser.parse_args()

    main(args.hal_path, args.output)
